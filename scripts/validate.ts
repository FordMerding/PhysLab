// Builds the "theory / numeric result / error" table and writes it to docs/VALIDATION.md.
//   npm run validate
import { writeFileSync, mkdirSync } from "node:fs";
import {
    allExperiments,
    atwoodForceReading,
    freeFallError,
    pendulumPeriodError,
    relError,
    tackleSweep,
} from "../tests/experiments";

const fmt = (x: number): string => (x === 0 ? "0" : Math.abs(x) < 1e-3 || Math.abs(x) >= 1e4 ? x.toExponential(3) : x.toPrecision(5));
const pct = (x: number): string => `${(x * 100).toFixed(x < 1e-4 ? 6 : 3)} %`;

const lines: string[] = [];
lines.push("# PhysLab validation");
lines.push("");
lines.push("Generated by `npm run validate`. Every row is an automated test (`npm test`): the test fails when the error exceeds the tolerance.");
lines.push("");
lines.push("Units: SI (m, kg, s, N). Engine settings: step 1/120 s, 4 substeps, 20 + 12 velocity iterations, 6 position iterations (defaults).");
lines.push("Relative error = |result - theory| / |theory|. Where the theory value is 0 the error column is absolute.");
lines.push("");
lines.push("## 1. Reference experiments");
lines.push("");
lines.push("| # | Experiment | Quantity | Theory | Result | Error | Tolerance | Status |");
lines.push("|---|---|---|---|---|---|---|---|");
let failed = 0;
allExperiments().forEach((e, i) => {
    const abs = e.theory === 0;
    const err = abs ? Math.abs(e.numeric) : relError(e.numeric, e.theory);
    const ok = err <= e.tolerance;
    if (!ok) failed++;
    const unit = e.unit ? ` ${e.unit}` : "";
    lines.push(
        `| ${i + 1} | ${e.title} | ${e.quantity} | ${fmt(e.theory)}${unit} | ${fmt(e.numeric)}${unit} | ${abs ? fmt(err) : pct(err)} | ${abs ? fmt(e.tolerance) : pct(e.tolerance)} | ${ok ? "pass" : "FAIL"} |`
    );
});
lines.push("");
lines.push("Parameters of each experiment:");
lines.push("");
allExperiments().forEach((e, i) => lines.push(`${i + 1}. **${e.title}**: ${e.setup}.${e.note ? ` _${e.note}._` : ""}`));

lines.push("");
lines.push("## 2. Convergence");
lines.push("");
lines.push("Free fall, distance after 1 s (theory 4.905 m). The scheme is first order in the substep:");
lines.push("");
lines.push("| Substeps | Absolute error, m |");
lines.push("|---|---|");
for (const s of [1, 2, 4, 8]) lines.push(`| ${s} | ${fmt(freeFallError(s))} |`);
lines.push("");
lines.push("Pendulum (L = 1 m, amplitude 0.3 rad), relative error of the period. Iterations change nothing: a rigid rod converges within a few iterations.");
lines.push("");
lines.push("| Substeps | Iterations | Relative error |");
lines.push("|---|---|---|");
for (const [s, it] of [[1, 5], [2, 10], [4, 20], [8, 40]]) lines.push(`| ${s} | ${it} | ${pct(pendulumPeriodError(s, it))} |`);

lines.push("");
lines.push("## 3. Dynamometer (force = impulse per step / step length)");
lines.push("");
lines.push("The force readout of a body is the sum of all joint and contact impulses applied to it during one 1/120 s step (all four substeps, warm-start included, position correction excluded) divided by 1/120 s.");
lines.push("Summed over time it reproduces Newton's second law to machine precision (`impulse balance` tests, difference < 1e-9 N s). A single step is noisy for light ropes, so use the time average or the smoothed value (`smoothForceX/Y`).");
lines.push("");
lines.push("Atwood machine, m1 = 2 kg, m2 = 1 kg: mean tension read on m1 (0.25-1 s) against the ideal 13.08 N. Theory neglects the rope mass.");
lines.push("");
lines.push("| Rope node mass, kg | Result, N | Ideal, N | a result, m/s^2 | a with rope mass, m/s^2 | Rope stretch |");
lines.push("|---|---|---|---|---|---|");
for (const m of [0.05, 0.01, 0.005, 0.002]) {
    const r = atwoodForceReading(m);
    lines.push(`| ${m} | ${fmt(r.mean)} | ${fmt(r.theory)} | ${fmt(r.a)} | ${fmt(r.aTheory)} | ${pct(Math.abs(r.stretch))} |`);
}

lines.push("");
lines.push("## 4. Known limitation: block and tackle with a light rope");
lines.push("");
lines.push("Movable pulley with load M, handle mass mh, rope over a fixed pulley (two rope segments carry the movable pulley).");
lines.push("Ideal theory: a(handle) = (mh - M/2) g / (mh + M/4). Acceleration is measured between 0.5 s and 0.9 s.");
lines.push("These rows are **not** pass/fail tests: they show where the chain-of-nodes rope is not accurate. Do not use quantitative readouts from this regime.");
lines.push("For textbook pulley problems use the ideal rope (the Pulley rope tool, `PulleyRope`, or the scenes Atwood machine and Block and tackle with an ideal rope): it has no mass and no stretch, and the ideal-rope and Pulley-rope rows above reproduce the formulas to better than 1 %.");
lines.push("");
lines.push("| Node mass, kg | M, kg | mh, kg | M / node mass | Rope mass, kg | Theory, m/s^2 | Result, m/s^2 | Error | Max stretch |");
lines.push("|---|---|---|---|---|---|---|---|---|");
for (const r of tackleSweep()) {
    lines.push(
        `| ${r.nodeMass} | ${r.load} | ${r.handle} | ${r.massRatio} | ${r.ropeMass.toFixed(2)} | ${fmt(r.theory)} | ${fmt(r.numeric)} | ${pct(r.error)} | ${pct(r.maxStretch)} |`
    );
}
lines.push("");
lines.push("The rope stays inextensible within about 2 %, but the startup transient (the rope stretches under the sudden load) and the weight and inertia of the rope itself decide the result. The rope mass here is comparable with the net driving force, so the ideal formula does not apply.");

mkdirSync("docs", { recursive: true });
writeFileSync("docs/VALIDATION.md", lines.join("\n") + "\n");
console.log(lines.join("\n"));
if (failed > 0) {
    console.error(`\n${failed} experiment(s) outside tolerance`);
    process.exit(1);
}
